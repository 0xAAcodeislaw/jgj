def write(rel: str, text: str) -> None:
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")


def save(rel: str, value) -> None:
    write(rel, json.dumps(value, ensure_ascii=False, indent=2) + "\n")


def normalize(text: str) -> str:
    return (
        text.replace("\n", "")
        .replace(" ", "")
        .replace("　", "")
        .replace("“", "「")
        .replace("”", "」")
        .replace("‘", "『")
        .replace("’", "』")
        .replace("无馀", "无余")
        .replace("须菩提言「", "须菩提言：「")
        .replace("佛言「", "佛言：「")
        .replace("波罗密", "波罗蜜")
    )


def chars(text: str) -> str:
    return "".join(re.findall(r"[\u3400-\u9fff]", text))


